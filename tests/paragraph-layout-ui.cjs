const { _electron } = require('playwright');
const fs = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
(async () => {
  const output = path.join(root, 'test-output'); await fs.mkdir(output, { recursive: true });
  const userData = await fs.mkdtemp(path.join(output, 'paragraph-layout-'));
  const project = { format: 'wraiter', version: 1, id: 'paragraph-layout-test', title: 'Paragraph layout', language: 'en-US', chapters: [{ id: 'first', title: 'First', content: { type: 'doc', content: [{ type: 'paragraph', attrs: { spaceAfter: 12 }, content: [{ type: 'text', text: 'First paragraph keeps its words and spacing.' }] }, { type: 'paragraph', attrs: { spaceAfter: 24 }, content: [{ type: 'text', text: 'Second paragraph has a different style.' }] }] } }] };
  await fs.writeFile(path.join(userData, 'settings.json'), JSON.stringify({ setupComplete: true, tutorialComplete: true, enabled: false, startup: 'restore', theme: 'paper', spellcheck: false }));
  await fs.writeFile(path.join(userData, 'recovery.json'), JSON.stringify({ project, path: null, expectedHash: null }));
  const env = { ...process.env, WRAITER_USER_DATA: userData }; delete env.ELECTRON_RUN_AS_NODE;
  let app;
  try {
    app = await _electron.launch(process.env.WRAITER_EXECUTABLE ? { executablePath: process.env.WRAITER_EXECUTABLE, args: [], env, timeout: 60000 } : { args: [root], env, timeout: 60000 });
    const page = await app.firstWindow(); page.setDefaultTimeout(10000); const errors = []; page.on('pageerror', error => errors.push(error.message));
    const editor = page.getByRole('textbox', { name: 'Manuscript editor', exact: true }); await editor.waitFor();
    const menu = label => app.evaluate(({ Menu }, label) => { const item = Menu.getApplicationMenu().items.find(item => item.label === '&Tools').submenu.items.find(item => item.label === label); if (!item) throw new Error('Missing menu ' + label); item.click(); }, label);
    const text = await editor.evaluate(el => el.editor.state.doc.textContent);
    await editor.evaluate(el => el.editor.commands.selectAll());
    await menu('Paragraph layout…');
    let dialog = page.getByRole('dialog', { name: 'Paragraph layout', exact: true }); await dialog.waitFor().catch(async error => { console.error('Paragraph failure', errors, await page.locator('body').innerText()); await page.screenshot({ path: path.join(output, 'paragraph-layout-failure.png') }); throw error; });
    await dialog.getByText('Applies to 2 selected paragraphs.').waitFor();
    await dialog.getByRole('spinbutton', { name: 'Left indent', exact: true }).fill('1.27');
    await dialog.getByRole('spinbutton', { name: 'First line', exact: true }).fill('-0.63');
    await dialog.getByRole('spinbutton', { name: 'Tab spacing', exact: true }).fill('2.54');
    await page.screenshot({ path: path.join(output, 'paragraph-layout-light.png') });
    await dialog.getByRole('button', { name: 'Apply layout', exact: true }).click();
    await dialog.waitFor({ state: 'hidden' });
    let result = await editor.evaluate(el => el.editor.state.doc.toJSON());
    assert.deepEqual(result.content.map(node => node.attrs.leftIndent), [36, 36]);
    assert.deepEqual(result.content.map(node => node.attrs.spaceAfter), [12, 24], 'Unchanged fields must retain mixed paragraph formatting');
    assert.deepEqual(result.content.map(node => node.attrs.tabStops), [[72], [72]]);
    assert.equal(await editor.evaluate(el => el.editor.state.doc.textContent), text);
    await editor.press('Control+z');
    await page.waitForFunction(() => document.querySelector('.manuscript').editor.state.doc.firstChild.attrs.leftIndent === null);
    await editor.press('Control+y');
    await page.waitForFunction(() => document.querySelector('.manuscript').editor.state.doc.firstChild.attrs.leftIndent === 36);
    await editor.evaluate(el => el.editor.commands.setTextSelection(6));
    await menu('Insert tab character');
    assert.ok((await editor.evaluate(el => el.editor.state.doc.textContent)).includes('\t'));
    await editor.press('Control+z');
    await page.waitForFunction(() => !document.querySelector('.manuscript').editor.state.doc.textContent.includes('\t'));
    await editor.evaluate(el => el.editor.commands.setTextSelection(6));
    await menu('Paragraph layout…');
    dialog = page.getByRole('dialog', { name: 'Paragraph layout', exact: true });
    await dialog.getByRole('button', { name: 'Reset to style defaults', exact: true }).click();
    result = await editor.evaluate(el => el.editor.state.doc.toJSON());
    assert.equal(result.content[0].attrs.leftIndent, null); assert.equal(result.content[1].attrs.leftIndent, 36);
    assert.equal(await editor.evaluate(el => el.editor.state.doc.textContent), text);
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(960, 650));
    await menu('Paragraph layout…'); await dialog.waitFor();
    await page.screenshot({ path: path.join(output, 'paragraph-layout-small.png') });
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
    assert.deepEqual(errors, []);
    console.log('Native paragraph menu, centimetre conversion, selected-paragraph scope, preservation of mixed formatting, tab insertion, reset and undo/redo passed.');
  } finally { await app?.close().catch(() => {}); }
})().catch(error => { console.error(error); process.exitCode = 1; });

