const { _electron } = require('playwright');
const fs = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
(async () => {
  const output = path.join(root, 'test-output'); await fs.mkdir(output, { recursive: true });
  const userData = await fs.mkdtemp(path.join(output, 'layout-tools-'));
  const paragraph = text => ({ type: 'paragraph', content: [{ type: 'text', text }] });
  const project = { format: 'wraiter', version: 1, id: 'layout-ui', title: 'Layout tools', language: 'en-US', chapters: [{ id: 'one', title: 'One', content: { type: 'doc', content: [paragraph('Before the table.'), { type: 'image', attrs: { src: 'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+j1ioAAAAASUVORK5CYII=', alt: 'A picture', width: 160, height: 90 } }, paragraph('The following prose should wrap beside the picture and remain unchanged through image formatting. '.repeat(4))] } }] };
  await fs.writeFile(path.join(userData, 'settings.json'), JSON.stringify({ setupComplete: true, tutorialComplete: true, enabled: false, startup: 'restore', spellcheck: false }));
  await fs.writeFile(path.join(userData, 'recovery.json'), JSON.stringify({ project, path: null, expectedHash: null }));
  const env = { ...process.env, WRAITER_USER_DATA: userData }; delete env.ELECTRON_RUN_AS_NODE;
  let app;
  try {
    app = await _electron.launch({ args: [root], env, timeout: 60000 });
    const page = await app.firstWindow(), errors = []; page.setDefaultTimeout(10000);
    page.on('pageerror', error => errors.push(error.message));
    const editor = page.getByRole('textbox', { name: 'Manuscript editor', exact: true }); await editor.waitFor();
    const text = await editor.evaluate(el => el.editor.state.doc.textContent);
    await editor.evaluate(el => el.editor.commands.setTextSelection(18));
    const tools = async () => { await page.getByRole('button', { name: 'Table tools', exact: true }).click(); return page.getByRole('dialog', { name: 'Table tools', exact: true }); };
    let dialog = await tools();
    await dialog.getByRole('spinbutton', { name: 'Rows', exact: true }).fill('2');
    await dialog.getByRole('spinbutton', { name: 'Columns', exact: true }).fill('3');
    await dialog.getByRole('checkbox', { name: 'Header row', exact: true }).uncheck();
    await dialog.getByRole('button', { name: 'Insert table', exact: true }).click();
    assert.equal(await editor.locator('tr').count(), 2); assert.equal(await editor.locator('td').count(), 6);
    const selectCells = async (anchor = 0, head = anchor) => editor.evaluate((el, indices) => {
      const cells = []; el.editor.state.doc.descendants((node, pos) => { if (['tableCell', 'tableHeader'].includes(node.type.name)) cells.push(pos); });
      return el.editor.commands.setCellSelection({ anchorCell: cells[indices[0]], headCell: cells[indices[1]] });
    }, [anchor, head]);
    const action = async label => { const dialog = await tools(); await dialog.getByRole('button', { name: label, exact: true }).click(); await dialog.waitFor({ state: 'hidden' }); };
    await selectCells(); await action('Toggle header row'); assert.equal(await editor.locator('th').count(), 3);
    await selectCells(); await action('Toggle header column'); assert.equal(await editor.locator('th').count(), 4);
    await selectCells(0, 1); await action('Merge selected cells');
    assert.equal(await editor.locator('tr').first().locator('th').count(), 2);
    assert.equal(await editor.locator('tr').first().locator('th').first().getAttribute('colspan'), '2');
    await selectCells(); await action('Split cell'); assert.equal(await editor.locator('tr').first().locator('th').count(), 3);
    await selectCells(); await action('Add row below'); assert.equal(await editor.locator('tr').count(), 3);
    await editor.press('Control+z'); await page.waitForFunction(() => document.querySelectorAll('.manuscript tr').length === 2);
    await selectCells(); await action('Add column after'); assert.equal(await editor.locator('tr').first().locator('th').count(), 4);
    await editor.press('Control+z'); await page.waitForFunction(() => document.querySelector('.manuscript tr')?.children.length === 3);
    await selectCells(); dialog = await tools(); await dialog.getByLabel('Cell background', { exact: true }).fill('#ffeecc');
    await dialog.getByRole('button', { name: 'Apply background', exact: true }).click();
    assert.equal(await editor.locator('th').first().getAttribute('data-cell-background'), '#ffeecc');
    assert.equal(await editor.locator('th').first().evaluate(el => el.style.backgroundColor), 'rgb(255, 238, 204)');
    await editor.press('Control+z'); await page.waitForFunction(() => !document.querySelector('.manuscript [data-cell-background]'));
    await selectCells(); dialog = await tools(); await dialog.getByLabel('Cell border colour', { exact: true }).fill('#112233');
    await dialog.getByRole('button', { name: 'Apply border colour', exact: true }).click();
    assert.equal(await editor.locator('th').first().getAttribute('data-cell-border'), '#112233');
    assert.equal(await editor.locator('th').first().evaluate(el => el.style.borderTopColor), 'rgb(17, 34, 51)');
    await editor.press('Control+z'); await page.waitForFunction(() => !document.querySelector('.manuscript [data-cell-border]'));
    await selectCells(); await action('Delete row'); assert.equal(await editor.locator('tr').count(), 1);
    await editor.press('Control+z'); await page.waitForFunction(() => document.querySelectorAll('.manuscript tr').length === 2);
    await selectCells(); await action('Delete column'); assert.equal(await editor.locator('tr').first().locator('th').count(), 2);
    await editor.press('Control+z'); await page.waitForFunction(() => document.querySelector('.manuscript tr')?.children.length === 3);
    await selectCells(); await action('Remove table'); assert.equal(await editor.locator('table').count(), 0);
    await editor.press('Control+z'); await editor.locator('table').waitFor();
    const imageDialog = async () => {
      await editor.evaluate(el => { let at; el.editor.state.doc.descendants((node, pos) => { if (node.type.name === 'image') at = pos; }); el.editor.commands.setNodeSelection(at); });
      await page.getByRole('button', { name: 'Image properties…', exact: true }).click();
      return page.getByRole('dialog', { name: 'Image properties', exact: true });
    };
    dialog = await imageDialog(); await dialog.getByLabel('Image text wrapping', { exact: true }).selectOption('left');
    await dialog.getByRole('button', { name: 'Apply image properties', exact: true }).click();
    assert.equal(await editor.locator('.image-node').getAttribute('data-image-wrap'), 'left');
    assert.equal(await editor.locator('.image-node').evaluate(el => getComputedStyle(el).float), 'left');
    const wrapped = await editor.locator('p').filter({ hasText: 'The following prose' }).evaluate(el => {
      const range = document.createRange(); range.setStart(el.firstChild, 0); range.setEnd(el.firstChild, 8);
      return range.getBoundingClientRect().left > el.previousElementSibling.getBoundingClientRect().right;
    });
    assert(wrapped, 'Text did not actually flow beside the left-wrapped image');
    await editor.press('Control+z'); await page.waitForFunction(() => !document.querySelector('.manuscript .image-node[data-image-wrap]'));
    await editor.press('Control+y'); await page.waitForFunction(() => document.querySelector('.manuscript .image-node')?.dataset.imageWrap === 'left');
    dialog = await imageDialog(); await dialog.getByLabel('Image text wrapping', { exact: true }).selectOption('right');
    await dialog.getByRole('button', { name: 'Apply image properties', exact: true }).click();
    assert.equal(await editor.locator('.image-node').evaluate(el => getComputedStyle(el).float), 'right');
    dialog = await imageDialog(); await dialog.getByLabel('Image text wrapping', { exact: true }).selectOption('inline');
    await dialog.getByRole('button', { name: 'Apply image properties', exact: true }).click();
    assert.equal(await editor.locator('.image-node').getAttribute('data-image-wrap'), null);
    assert.equal(await editor.evaluate(el => el.editor.state.doc.textContent), text);
    assert.deepEqual(errors, []);
    console.log('Table insertion, headers, merge/split, rows/columns, cell colours, removal, image left/right flow and undo/redo passed.');
  } finally { await app?.close().catch(() => {}); }
})().catch(error => { console.error(error); process.exitCode = 1; });
