const { _electron } = require('playwright');
const fs = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
(async () => {
  const output = path.join(root, 'test-output'); await fs.mkdir(output, { recursive: true });
  const userData = await fs.mkdtemp(path.join(output, 'notes-ui-'));
  const project = { format: 'wraiter', version: 1, id: 'note-ui', title: 'Note UI', language: 'en-US', chapters: [{ id: 'one', title: 'One', content: { type: 'doc', content: [{ type: 'paragraph', content: [{ type: 'text', text: 'one ' }, { type: 'text', text: 'two', marks: [{ type: 'bold' }] }, { type: 'text', text: ' three' }] }] } }] };
  await fs.writeFile(path.join(userData, 'settings.json'), JSON.stringify({ setupComplete: true, tutorialComplete: true, enabled: false, startup: 'restore' }));
  await fs.writeFile(path.join(userData, 'recovery.json'), JSON.stringify({ project, path: null, expectedHash: null }));
  const env = { ...process.env, WRAITER_USER_DATA: userData }; delete env.ELECTRON_RUN_AS_NODE;
  let app;
  try {
    app = await _electron.launch(process.env.WRAITER_EXECUTABLE ? { executablePath: process.env.WRAITER_EXECUTABLE, args: [], env, timeout: 60000 } : { args: [root], env, timeout: 60000 });
    const page = await app.firstWindow(); page.setDefaultTimeout(10000);
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    const menu = labels => app.evaluate(({ Menu }, labels) => { let items = Menu.getApplicationMenu().items, item; for (const label of labels) { item = items.find(item => item.label.replaceAll('&', '') === label); if (!item) throw new Error('Missing menu: ' + label); items = item.submenu?.items; } item.click(); }, labels);
    const editor = page.getByRole('textbox', { name: 'Manuscript editor', exact: true }); await editor.waitFor();
    await editor.evaluate(el => el.editor.commands.setTextSelection({ from: 5, to: 8 }));
    await menu(['Tools', 'Footnotes and endnotes', 'Insert footnote…']);
    await page.getByLabel('Note text', { exact: true }).fill('A footnote');
    assert.equal(await page.getByLabel('Note text', { exact: true }).inputValue(), 'A footnote');
    await page.getByRole('button', { name: 'Insert note', exact: true }).click();
    assert.equal(await editor.evaluate(el => el.editor.state.doc.textContent), 'one two three');
    assert.equal(await editor.locator('.note-marker').count(), 1);
    assert.equal(await editor.locator('strong').innerText(), 'two');
    assert.equal(await editor.locator('.note-marker').getAttribute('data-note-text'), 'A footnote');
    await editor.press('Control+z');
    await page.waitForFunction(() => !document.querySelector('.manuscript .note-marker'));
    assert.equal(await editor.evaluate(el => el.editor.state.doc.textContent), 'one two three');
    await editor.press('Control+y');
    await editor.locator('.note-marker').waitFor({ state: 'attached' });
    await editor.locator('.note-marker').click();
    assert.equal(await page.getByLabel('Note text', { exact: true }).inputValue(), 'A footnote');
    await page.getByLabel('Note type', { exact: true }).selectOption('endnote');
    await page.getByLabel('Note text', { exact: true }).fill('An edited endnote');
    await page.getByRole('button', { name: 'Save note', exact: true }).click();
    assert.equal(await editor.locator('.note-marker').getAttribute('data-note-kind'), 'endnote');
    assert.equal(await editor.evaluate(el => el.editor.state.doc.textContent), 'one two three');
    const markerStyle = await editor.locator('.note-marker').evaluate(el => ({ fontSize: getComputedStyle(el).fontSize, content: getComputedStyle(el, '::after').content }));
    assert.equal(markerStyle.fontSize, '0px');
    assert.match(markerStyle.content, /counter\(manuscript-endnote, lower-roman\)/);
    await page.screenshot({ path: path.join(output, 'notes-ui.png') });
    await menu(['Tools', 'Footnotes and endnotes', 'Manage document notes…']);
    await page.getByRole('button', { name: /Endnote 1 An edited endnote/ }).click();
    await page.screenshot({ path: path.join(output, 'note-redesign.png') });
    await page.getByRole('button', { name: 'Delete note', exact: true }).click();
    assert.equal(await editor.locator('.note-marker').count(), 0);
    assert.equal(await editor.evaluate(el => el.editor.state.doc.textContent), 'one two three');
    await editor.press('Control+z'); await editor.locator('.note-marker').waitFor();
    assert.equal(await editor.locator('.note-marker').getAttribute('data-note-text'), 'An edited endnote');
    assert.deepEqual(errors, []);
    console.log('Native note menu, preserved prose/formatting, undo/redo, direct marker editing, note manager and deletion passed.');
  } finally { await app?.close().catch(() => {}); }
})().catch(error => { console.error(error); process.exitCode = 1; });
